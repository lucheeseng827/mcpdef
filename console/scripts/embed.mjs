// After `vite build`: give each file of the built console, in the
// mcpdef-console crate's assets/, its brotli and gzip forms, and write the
// table the crate serves them from (src/assets.rs). So `cargo build` needs
// neither Node nor a build dependency, and the table is reviewed like code.
//
// The output is a function of the input alone: files in sorted order, the
// compressors' settings fixed, and no time or path of this machine in it. CI
// builds again and diffs, so what is committed is what this script writes.

import { readdirSync, readFileSync, writeFileSync, statSync, mkdirSync, copyFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { brotliCompressSync, gzipSync, constants } from "node:zlib";
import { dirname, join, relative, extname, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const console_ = join(here, "..");
const crate = join(console_, "..", "crates", "mcpdef-console");
const assets = join(crate, "assets");

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".txt": "text/plain; charset=utf-8",
  ".woff2": "font/woff2",
  ".png": "image/png",
  ".ico": "image/x-icon",
};
// What compresses: text. A woff2 or a png is compressed already.
const TEXT = new Set([".html", ".js", ".css", ".svg", ".json", ".txt"]);

function walk(dir) {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory() ? walk(path) : [path];
    })
    .filter((path) => !path.endsWith(".br") && !path.endsWith(".gz"));
}

const rust = (s) => JSON.stringify(s);
const entries = [];
for (const file of walk(assets)) {
  const rel = relative(assets, file).split(sep).join("/");
  const ext = extname(file);
  const type = TYPES[ext];
  if (!type) throw new Error(`${rel}: no content type for ${ext}`);
  const body = readFileSync(file);
  const etag = `"${createHash("sha256").update(body).digest("hex").slice(0, 32)}"`;
  const variants = {};
  if (TEXT.has(ext)) {
    const br = brotliCompressSync(body, {
      params: {
        [constants.BROTLI_PARAM_MODE]: constants.BROTLI_MODE_TEXT,
        [constants.BROTLI_PARAM_QUALITY]: constants.BROTLI_MAX_QUALITY,
        [constants.BROTLI_PARAM_SIZE_HINT]: body.length,
      },
    });
    const gz = gzipSync(body, { level: 9 });
    // A form no smaller is not worth a byte of the binary.
    if (br.length < body.length) {
      writeFileSync(file + ".br", br);
      variants.br = rel + ".br";
    }
    if (gz.length < body.length) {
      writeFileSync(file + ".gz", gz);
      variants.gzip = rel + ".gz";
    }
  }
  // Vite names what it emits under assets/ by its hash: a new build, a new name.
  const immutable = rel.startsWith("assets/");
  entries.push({ path: "/" + rel, rel, type, etag, immutable, ...variants });
}
if (!entries.some((e) => e.path === "/index.html")) throw new Error("no index.html: run `vite build` first");

const bytes = (rel) => `include_bytes!(${rust("../assets/" + rel)})`;
const table = entries
  .map(
    (e) => `    Asset {
        path: ${rust(e.path)},
        content_type: ${rust(e.type)},
        etag: ${rust(e.etag)},
        immutable: ${e.immutable},
        identity: ${bytes(e.rel)},
        br: ${e.br ? `Some(${bytes(e.br)})` : "None"},
        gzip: ${e.gzip ? `Some(${bytes(e.gzip)})` : "None"},
    },
`
  )
  .join("");
writeFileSync(
  join(crate, "src", "assets.rs"),
  `// SPDX-License-Identifier: Apache-2.0
// @generated by console/scripts/embed.mjs from the console's build: do not
// edit. \`npm run build\` in console/ writes it again.

/// Every file of the built console, sorted by path.
pub static ASSETS: &[Asset] = &[
${table}];
`
);

// The licenses of what the build bundles, which go where it goes. Named so
// that the repository's ignore rules, which drop *.txt but keep OFL*.txt,
// keep every one: the crate is packaged from what is committed.
const licenses = join(crate, "licenses");
mkdirSync(licenses, { recursive: true });
copyFileSync(join(console_, "src", "ds", "fonts", "OFL.txt"), join(licenses, "OFL-1.1-IBM-Plex.txt"));
for (const pkg of ["react", "react-dom", "scheduler"]) {
  copyFileSync(join(console_, "node_modules", pkg, "LICENSE"), join(licenses, `${pkg}.LICENSE`));
}

const total = entries.reduce((n, e) => n + readFileSync(join(assets, e.rel)).length, 0);
console.log(`embed: ${entries.length} files, ${total} bytes, into ${relative(console_, crate)}`);
